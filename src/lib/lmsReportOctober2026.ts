export const OCTOBER_TOP_OVERALL_TEACHERS = OCTOBER_2026_LMS_TEACHERS.filter(
  t => t.category === 'top_overall' || (t.generalIndex && t.generalIndex >= 85)
);

export const OCTOBER_TOP_DEPT_TEACHERS = OCTOBER_2026_LMS_TEACHERS.filter(
  t => t.category === 'top_dept' || t.badges.some(b => b.includes('فارس'))
);

export const OCTOBER_TOP_LESSONS_TEACHERS = [...OCTOBER_2026_LMS_TEACHERS]
  .filter(t => t.lessonsUploaded > 0)
  .sort((a, b) => (b.lessonsIndex || 0) - (a.lessonsIndex || 0))
  .slice(0, 15);

export const OCTOBER_TOP_GRADED_TEACHERS = [...OCTOBER_2026_LMS_TEACHERS]
  .filter(t => t.submissionsReceived > 0)
  .sort((a, b) => b.submissionsGraded - a.submissionsGraded)
  .slice(0, 10);

export const OCTOBER_FOLLOWUP_PENDING_TEACHERS = OCTOBER_2026_LMS_TEACHERS.filter(
  t => (t.evalIndex !== undefined && t.evalIndex < 55) || t.submissionsPending > 20
).sort((a, b) => b.submissionsPending - a.submissionsPending);

export const OCTOBER_FOLLOWUP_PARTIAL_TEACHERS = OCTOBER_2026_LMS_TEACHERS.filter(
  t => t.evalCoveragePercent > 0 && t.evalCoveragePercent < 100
);

export const OCTOBER_UNASSIGNED_EVAL_TEACHERS = OCTOBER_2026_LMS_TEACHERS.filter(
  t => t.evalUnassigned > 0
);

export const OCTOBER_ZERO_LESSON_TEACHERS = OCTOBER_2026_LMS_TEACHERS.filter(
  t => t.hasActivityData && t.lessonsUploaded === 0
);

export function generateOctober2026Evaluations(teachers: any[]): any[] {
  const out: any[] = [];
  let eIdx = 9500;

  OCTOBER_2026_LMS_TEACHERS.forEach(lmsT => {
    const t = teachers.find(
      x =>
        x.nameAr === lmsT.name ||
        x.nameAr.includes(lmsT.name) ||
        lmsT.name.includes(x.nameAr) ||
        (x.nameEn && lmsT.name.toLowerCase().includes(x.nameEn.toLowerCase()))
    );
    if (!t) return;

    let totalScore = 80;
    let perfLabel = 'جيد جداً';

    if (lmsT.generalIndex && lmsT.generalIndex > 0) {
      totalScore = Math.round(lmsT.generalIndex * 10) / 10;
      perfLabel = totalScore >= 85 ? 'متميز' : totalScore >= 70 ? 'جيد' : totalScore >= 55 ? 'مقبول' : 'يحتاج إلى متابعة وخطة تحسين';
    } else if (lmsT.evalIndex && lmsT.evalIndex > 0) {
      totalScore = Math.round(lmsT.evalIndex * 10) / 10;
      perfLabel = totalScore >= 85 ? 'متميز' : totalScore >= 70 ? 'جيد' : totalScore >= 55 ? 'مقبول' : 'يحتاج إلى متابعة وخطة تحسين';
    } else if (lmsT.adminRating === 'ممتاز') {
      totalScore = 95;
      perfLabel = 'متميز';
    } else if (lmsT.adminRating === 'جيد جداً') {
      totalScore = 85;
      perfLabel = 'جيد جداً';
    }

    const avgScore = Math.round((totalScore / 5) * 10) / 10;
    const critScore = Math.round((totalScore / 5) * 10) / 10;

    const criteria = [
      {
        score: critScore,
        note: 'الدروس: ' + lmsT.lessonsUploaded + ' مرفوعة (' + lmsT.lessonsVisible + ' ظاهرة للطلبة، ' + (lmsT.lessonsValidPercent || 100) + '% استيفاء)',
      },
      {
        score: critScore,
        note: 'التقييمات: ' + (lmsT.evalUploaded > 0 ? lmsT.evalUploaded + ' تقييمات (' + lmsT.evalAssigned + ' مسندة)' : 'تقرير الدروس والمقررات التخصصية'),
      },
      {
        score: critScore,
        note: 'التصحيح: ' + lmsT.submissionsGraded + '/' + lmsT.submissionsReceived + ' (' + lmsT.gradingRate + '% إتمام التصحيح)',
      },
      {
        score: critScore >= 14 ? 20 : 0,
        note: lmsT.evalAssigned > 0 ? 'تم إسناد التقييمات ومتابعتها' : 'مطلوب إسناد التقييمات الأسبوعية للطلاب',
      },
      {
        score: critScore,
        note: 'نسبة حل الطلبة: ' + lmsT.solveRate + '%',
      },
      {
        score: 0,
        note: lmsT.notes,
        value: 'نعم',
      },
    ];

    out.push({
      id: 'lms_oct_ev_' + eIdx++,
      teacherId: t.id,
      evaluatorId: 'u1',
      month: 'أكتوبر',
      academicYear: '2026-2027',
      term: 'الفصل الأول',
      evaluationDate: '2026-10-23',
      criteria,
      totalScore,
      averageScore: avgScore,
      percentage: totalScore,
      performanceLevel: perfLabel,
      strengths: lmsT.badges.join(' • ') || 'متابعة النشاط على المنصة وفق التقرير المعتمد لأكتوبر 2026',
      improvementAreas:
        lmsT.submissionsPending > 0
          ? 'استكمال تصحيح ' + lmsT.submissionsPending + ' تسليماً معلقاً متراكماً'
          : lmsT.evalUnassigned > 0
          ? 'إسناد ' + lmsT.evalUnassigned + ' تقييمات غير مسندة للطلاب'
          : 'الاستمرار في الحفاظ على هذا المستوى المتميز ومشاركة الممارسات النموذجية',
      recommendations: lmsT.notes,
      actionPlan:
        lmsT.submissionsPending > 0
          ? 'تصحيح التسليمات المعلقة (' + lmsT.submissionsPending + ' تسليماً) والالتزام بالتصحيح خلال 3 أيام ومتابعة الطلبة غير المستجيبين'
          : lmsT.evalUnassigned > 0
          ? 'إسناد التقييمات المنشأة غير المسندة للطلاب وتفعيل متابعة الاستجابات'
          : 'مشاركة الممارسات الرقمية النموذجية مع الزملاء بالقسم',
      hasWeeklyAssignment: lmsT.evalAssigned > 0,
      evidenceLinks: [],
      generalNotes: lmsT.notes,
      createdAt: '2026-10-23T10:00:00Z',
      updatedAt: '2026-10-23T10:00:00Z',
    });
  });

  return out;
}
