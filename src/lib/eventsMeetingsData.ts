// LocalStorage Persistence Key
const LOCAL_STORAGE_KEY = 'qstss_events_meetings_data_v2';

export function loadEventsMeetings(): EventMeetingItem[] {
  if (typeof window === 'undefined') return INITIAL_EVENTS_MEETINGS;
  try {
    const saved = localStorage.getItem(LOCAL_STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Error loading events & meetings from localStorage:', err);
  }
  return INITIAL_EVENTS_MEETINGS;
}

export function saveEventsMeetings(items: EventMeetingItem[]): void {
  if (typeof window === 'undefined') return;
  try {
    localStorage.setItem(LOCAL_STORAGE_KEY, JSON.stringify(items));
  } catch (err) {
    console.error('Error saving events & meetings to localStorage:', err);
  }
}
